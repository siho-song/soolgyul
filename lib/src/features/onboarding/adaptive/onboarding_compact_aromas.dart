  /// The lists of a drink's category and kind. A kind not singled out below,
  /// or no kind, gets its category's widest lists: red wine, single malt,
  /// 탁주. An unknown category gets the red wine lists.
  factory OnboardingCompactAromas.forDrink(
    String? categoryKey,
    String? styleKey,
  ) {
    final name = switch (categoryKey) {
      'wine' when _whiteWines.contains(styleKey) => 'wine_white_sparkling',
      'wine' when _roseWines.contains(styleKey) => 'wine_rose_natural',
      'whisky' when _bourbonAndBlended.contains(styleKey) =>
        'whisky_bourbon_blended',
      'whisky' => 'whisky_single_malt',
      'sake' => 'sake',
      'korean_traditional' => switch (styleKey) {
        'yakju' || 'korean_cheongju' || 'gwahaju' => 'korean_yakju_cheongju',
        'distilled_soju' || 'diluted_soju' => 'korean_distilled_soju',
        'korean_fruit_wine' => 'korean_fruit_wine',
        _ => 'korean_takju',
      },
      _ => 'wine_red',
    };
    final (:palate, :finish) = _lists[name]!;
    return OnboardingCompactAromas._(name, palate, finish);
  }

