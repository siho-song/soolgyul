"""Generate/check deployment copies of the ONE taxonomy-owned rule contract."""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import re

from tools.catalog.enrichment.materialize_catalog_terms import materialize_catalog_terms
from tools.catalog.enrichment.taxonomy import load_and_validate_taxonomy

ROOT = Path(__file__).resolve().parents[3]
JSON_PATH = ROOT / "supabase/functions/_shared/catalog/assignment_contract.json"
DART_PATH = ROOT / "lib/src/core/catalog/assignment_contract.g.dart"
TS_KEYS_PATH = ROOT / "supabase/functions/_shared/catalog/assignment_keys.g.ts"
PY_KEYS_PATH = ROOT / "tools/catalog/enrichment/assignment_keys_generated.py"


def compile_contract() -> dict:
    taxonomy, _ = load_and_validate_taxonomy()
    terms = []
    for row in materialize_catalog_terms():
        if row['term_type'] not in {'style', 'ingredient', 'process', 'maturation'}:
            continue
        m = row['metadata']
        terms.append({'kind': row['term_type'], 'key': row['term_key'],
                      'categories': sorted(m['applies_to_categories']),
                      'styles': sorted(m.get('applies_to_styles', [])),
                      'target': m.get('allowed_target', 'both'),
                      'excludes': sorted(m.get('excludes_term_keys', []))})
    body = {'schema_version': 2, 'taxonomy_version': taxonomy['taxonomy_version'],
            'categories': sorted(c['category_key'] for c in taxonomy['categories']),
            'terms': sorted(terms, key=lambda t: (t['kind'], t['key']))}
    digest = sha256(json.dumps(body, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    return {**body, 'contract_sha256': digest}


def enum_groups(contract):
    groups = [('CatalogCategoryKey', contract['categories'])]
    for name, kinds in [('CatalogStyleKey', {'style'}),
                        ('CatalogIngredientKey', {'ingredient'}),
                        ('CatalogProcessKey', {'process', 'maturation'})]:
        groups.append((name, sorted(t['key'] for t in contract['terms'] if t['kind'] in kinds)))
    for name, keys in groups:
        if len(keys) != len(set(keys)) or len(keys) != len({identifier(k) for k in keys}):
            raise ValueError(f'Enum key/member collision in {name}')
    return groups


def identifier(key):
    parts = re.split('[_:]', key)
    return parts[0] + ''.join(p.title() for p in parts[1:])


def dart_enums(groups):
    chunks = []
    for name, keys in groups:
        members = ',\n'.join(f"  {identifier(key)}('{key}')" for key in keys)
        chunks.append(f"enum {name} {{\n{members};\n"
                      f"  const {name}(this.key);\n  final String key;\n"
                      f"  static final _byKey = {{for (final v in values) v.key: v}};\n"
                      f"  static {name}? fromKey(String key) => _byKey[key];\n}}\n")
    return '\n'.join(chunks)


def ts_enums(groups):
    chunks = []
    for name, keys in groups:
        members = '\n'.join(f'  {identifier(k)[0].upper()+identifier(k)[1:]} = "{k}",' for k in keys)
        chunks.append(f'export enum {name} {{\n{members}\n}}\n')
    return '\n'.join(chunks)


def python_enums(groups):
    chunks = ['from enum import Enum\n\nclass _CatalogKey(str, Enum):\n    def __str__(self):\n        return self.value\n']
    for name, keys in groups:
        members = '\n'.join(f'    {key.replace(":", "__").upper()} = "{key}"' for key in keys)
        chunks.append(f'class {name}(_CatalogKey):\n{members}\n')
    return '\n\n'.join(chunks)


def generated_files() -> dict[Path, str]:
    contract = compile_contract()
    groups = enum_groups(contract)
    payload = json.dumps(contract, ensure_ascii=False, indent=2) + "\n"
    return {JSON_PATH: payload,
            DART_PATH: "// GENERATED. Run python3 -m tools.catalog.enrichment.generate_assignment_contract\n"
                       "// Do not edit: catalog/dictionary/terms.json owns these rules.\n"
                       "// dart format off\n"
                       + dart_enums(groups) + "\nconst catalogAssignmentContract = <String, dynamic>" + payload.rstrip() + ";\n",
            TS_KEYS_PATH: '// GENERATED by tools.catalog.enrichment.generate_assignment_contract. Do not edit.\n// deno-fmt-ignore-file\n' + ts_enums(groups),
            PY_KEYS_PATH: '# GENERATED by tools.catalog.enrichment.generate_assignment_contract. Do not edit.\n' + python_enums(groups)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in generated_files().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("Stale assignment contract: " + ", ".join(stale))
    print("Assignment contract: " + ("in sync" if args.check else "generated"))


if __name__ == "__main__":
    main()
